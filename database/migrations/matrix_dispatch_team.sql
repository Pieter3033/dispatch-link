/*
    Dispatch Link - add the Matrix dispatch team.

    The login account is provisioned separately because its Argon2 password
    hash is generated by SQLPage and must never be stored in source control.
*/

USE [CC];
GO

SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

IF OBJECT_ID(N'dbo.DispatchTeams', N'U') IS NULL
    THROW 51000, 'dbo.DispatchTeams must exist before adding Matrix.', 1;
GO

IF COL_LENGTH(N'dbo.DispatchTeams', N'MonthlyDispatchLimit') IS NULL
    ALTER TABLE dbo.DispatchTeams ADD MonthlyDispatchLimit int NULL;
GO

IF EXISTS (SELECT 1 FROM dbo.DispatchTeams WHERE TeamCode = N'REN' + N'TRAK')
   AND NOT EXISTS (SELECT 1 FROM dbo.DispatchTeams WHERE TeamCode = N'Matrix')
BEGIN
    UPDATE dbo.DispatchTeams
    SET TeamCode = N'Matrix',
        TeamName = N'Matrix',
        GroupUsername = N'eta_matrix',
        IsActive = 1,
        DisplayOrder = 40,
        MonthlyDispatchLimit = 150,
        UpdatedAt = SYSDATETIME(),
        UpdatedBy = N'migration'
    WHERE TeamCode = N'REN' + N'TRAK';
END
ELSE IF NOT EXISTS (SELECT 1 FROM dbo.DispatchTeams WHERE TeamCode = N'Matrix')
BEGIN
    INSERT INTO dbo.DispatchTeams
        (TeamCode, TeamName, GroupUsername, IsActive, DisplayOrder, MonthlyDispatchLimit, CreatedBy)
    VALUES
        (N'Matrix', N'Matrix', N'eta_matrix', 1, 40, 150, N'migration');
END
ELSE
BEGIN
    UPDATE dbo.DispatchTeams
    SET TeamName = N'Matrix',
        GroupUsername = N'eta_matrix',
        IsActive = 1,
        DisplayOrder = 40,
        MonthlyDispatchLimit = 150,
        UpdatedAt = SYSDATETIME(),
        UpdatedBy = N'migration'
    WHERE TeamCode = N'Matrix';
END;
GO

IF OBJECT_ID(N'dbo.CK_DispatchTeams_MonthlyLimit', N'C') IS NULL
    ALTER TABLE dbo.DispatchTeams WITH CHECK
        ADD CONSTRAINT CK_DispatchTeams_MonthlyLimit
        CHECK (MonthlyDispatchLimit IS NULL OR MonthlyDispatchLimit > 0);
GO

IF OBJECT_ID(N'dbo.DispatchAssignments', N'U') IS NOT NULL
BEGIN
    IF OBJECT_ID(N'dbo.CK_DispatchAssignments_Team', N'C') IS NOT NULL
        ALTER TABLE dbo.DispatchAssignments DROP CONSTRAINT CK_DispatchAssignments_Team;

    UPDATE dbo.DispatchAssignments
    SET AssignedTeam = N'Matrix',
        UpdatedAt = SYSDATETIME(),
        UpdatedBy = N'migration'
    WHERE AssignedTeam = N'Ren' + N'trak';

    ALTER TABLE dbo.DispatchAssignments WITH CHECK
        ADD CONSTRAINT CK_DispatchAssignments_Team
        CHECK (AssignedTeam IN (N'Capital Air', N'Private & Confidential', N'CSG', N'Matrix'));
END;
GO

IF COL_LENGTH(N'dbo.DispatchIncidents', N'DispatchTeam') IS NOT NULL
BEGIN
    UPDATE dbo.DispatchIncidents
    SET DispatchTeam = N'Matrix',
        UpdatedAt = SYSDATETIME(),
        UpdatedBy = N'migration'
    WHERE DispatchTeam = N'Ren' + N'trak';
END;
GO

PRINT 'Matrix dispatch-team configuration installed.';
GO
